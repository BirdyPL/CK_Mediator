// ===== Apply translations =====
const I18N_LS_KEY = "ck-mediator-lang";

function applyLang(lang) {
  if (!I18N[lang]) lang = "en";
  const dict = I18N[lang];
  document.body.setAttribute("data-lang", lang);
  document.documentElement.setAttribute("lang", lang === "zh" ? "zh-CN" : "en");

  // Text content
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    const val = dict[key];
    if (val !== undefined) el.textContent = val;
  });

  // Attribute translations: data-i18n-attr="placeholder|key.name"
  document.querySelectorAll("[data-i18n-attr]").forEach((el) => {
    const spec = el.getAttribute("data-i18n-attr");
    spec.split(",").forEach((pair) => {
      const [attr, key] = pair.split("|").map((s) => s.trim());
      if (attr && key && dict[key] !== undefined) el.setAttribute(attr, dict[key]);
    });
  });

  // Toggle buttons
  document.querySelectorAll("[data-lang-btn]").forEach((b) => {
    const on = b.getAttribute("data-lang-btn") === lang;
    b.classList.toggle("is-on", on);
    b.setAttribute("aria-pressed", on ? "true" : "false");
  });

  // Re-render dynamic UI bits that depend on language
  if (window.__renderScope) window.__renderScope();
  if (window.__updateProgress) window.__updateProgress();

  try { localStorage.setItem(I18N_LS_KEY, lang); } catch (e) {}
}

function t(key, vars) {
  const lang = document.body.getAttribute("data-lang") || "en";
  let s = (I18N[lang] && I18N[lang][key]) || (I18N.en[key] || key);
  if (vars) Object.keys(vars).forEach((k) => { s = s.replace("{" + k + "}", vars[k]); });
  return s;
}
window.t = t;

// Init
(function initI18n() {
  let saved = "en";
  try { saved = localStorage.getItem(I18N_LS_KEY) || "en"; } catch (e) {}
  if (!I18N[saved]) saved = "en";
  applyLang(saved);

  document.querySelectorAll("[data-lang-btn]").forEach((b) => {
    b.addEventListener("click", () => applyLang(b.getAttribute("data-lang-btn")));
  });
})();
